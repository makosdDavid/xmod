export const STRINGS = { en, hu };
export const MAP_KEYS = Object.keys(en);

export function format(s, params) {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] === undefined || params[k] === null ? m : String(params[k])));
}

// t(key, params) for one of the bundled languages (unknown language / key -> English)
export function createTranslator(lang = "en") {
  const table = STRINGS[lang] || en;
  return (key, params) => format(table[key] ?? en[key] ?? key, params);
}

// wraps a host translator so that missing keys fall back to English
export function withFallback(t) {
  const base = createTranslator("en");
  if (typeof t !== "function") return base;
  return (key, params) => {
    let s;
    try { s = t(key, params); } catch (e) { s = null; }
    return (s === undefined || s === null || s === key) ? base(key, params) : String(s);
  };
}
